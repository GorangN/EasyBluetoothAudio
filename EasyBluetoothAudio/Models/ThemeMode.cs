namespace EasyBluetoothAudio.Models;

/// <summary>
/// Defines the available application theme modes.
/// </summary>
public enum AppThemeMode
{
    /// <summary>
    /// Light color scheme.
    /// </summary>
    Light,

    /// <summary>
    /// Dark color scheme.
    /// </summary>
    Dark,

    /// <summary>
    /// Follows the operating system theme preference.
    /// </summary>
    System,

    /// <summary>
    /// The original industrial appearance with a dark background.
    /// </summary>
    RetroDark,

    /// <summary>
    /// A light version of the original industrial appearance.
    /// </summary>
    RetroLight
}
